#!/usr/bin/env bash
# Generate db/zm_config.sql: the Config rows a fresh ZoneMinder install has.
#
# ZoneMinder's build runs zmconfgen.pl, which appends one INSERT per option in
# ConfigData.pm to the packaged zm_create.sql. zm_create.sql.in, which this
# repo mirrors, has none of them, so a test database loaded from it had an
# empty Config table and code reading Config only ever saw its fallbacks.
# This runs ZoneMinder's own zmconfgen.pl from a source checkout, with the
# build values the Debian package uses, and keeps the generated section.
#
# Usage: scripts/generate-zm-config.sh /path/to/zoneminder [git-ref]
#   git-ref defaults to origin/master. Regenerate when the schema mirror moves
#   to a new ZoneMinder version.
set -euo pipefail

src="${1:?usage: $0 /path/to/zoneminder [git-ref]}"
ref="${2:-origin/master}"
here="$(cd "$(dirname "$0")/.." && pwd)"
out="$here/db/zm_config.sql"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

show() { git -C "$src" show "$ref:$1"; }
version="$(show version.txt | tr -d '[:space:]')"
commit="$(git -C "$src" rev-parse --short "$ref")"

# configure_file(@ONLY) as the Debian package's build sets it.
subst() {
  sed -e "s|@VERSION@|$version|g" \
      -e "s|@OPT_FFMPEG@|yes|g" \
      -e "s|@PATH_FFMPEG@|/usr/bin/ffmpeg|g" \
      -e "s|@ZM_CONFIG_SUBDIR@|/etc/zm/conf.d|g" \
      -e "s|@ZM_CONTENTDIR@|/var/cache/zoneminder|g" \
      -e "s|@ZM_FONTDIR@|/usr/share/zoneminder/fonts|g" \
      -e "s|@ZM_TMPDIR@|/tmp/zm|g" \
      -e "s|@ZM_WEB_USER@|www-data|g" \
      -e "s|@CMAKE_BINARY_DIR@|$work|g" \
      -e "s|@CMAKE_CURRENT_BINARY_DIR@|$work|g" \
      -e "s|@PERL_EXECUTABLE@|perl|g"
}

lib="$work/scripts/ZoneMinder/lib/ZoneMinder"
mkdir -p "$lib" "$work/db"
show scripts/ZoneMinder/lib/ZoneMinder/Base.pm.in | subst >"$lib/Base.pm"
show scripts/ZoneMinder/lib/ZoneMinder/ConfigData.pm.in | subst >"$lib/ConfigData.pm"
show zmconfgen.pl.in | subst >"$work/zmconfgen.pl"
: >"$work/db/zm_create.sql"
perl "$work/zmconfgen.pl" >/dev/null

{
  echo "-- Config rows of a fresh ZoneMinder $version install (zoneminder $commit)."
  echo "-- Generated by scripts/generate-zm-config.sh from ZoneMinder's zmconfgen.pl;"
  echo "-- do not edit. Loaded after zm_create.sql.in by scripts/setup-ci-db.sh."
  echo
  sed -n '/^-- This section is autogenerated/,$p' "$work/db/zm_create.sql" \
    | grep -v '^--' | sed '/./,$!d'
} >"$out"
echo "Wrote $out: $(grep -c '^INSERT INTO Config' "$out") options from ZoneMinder $version ($commit)"
